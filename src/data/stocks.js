function buildTimeframeSeries(stock) {
  const h1Y = stock.history
  const g = stock.annualGrowthPct / 100
  const back3Y = []
  const back5Y = []

  // Build deterministic smooth 3Y (12 quarters) and 5Y (10 half-year points)
  for (let i = 11; i >= 0; i -= 1) {
    const yearsBack = i / 4
    const wave = 1 + Math.sin(i * 1.1 + stock.priceUSD) * 0.04
    back3Y.push(Number(((stock.priceUSD / Math.pow(1 + g, yearsBack)) * wave).toFixed(4)))
  }
  back3Y[back3Y.length - 1] = stock.priceUSD

  for (let i = 9; i >= 0; i -= 1) {
    const yearsBack = i * 0.5
    const wave = 1 + Math.cos(i * 0.9 + stock.peRatio) * 0.05
    back5Y.push(Number(((stock.priceUSD / Math.pow(1 + g, yearsBack)) * wave).toFixed(4)))
  }
  back5Y[back5Y.length - 1] = stock.priceUSD

  return {
    '3M': h1Y.slice(-4),
    '6M': h1Y.slice(-6),
    '1Y': h1Y,
    '3Y': back3Y,
    '5Y': back5Y,
  }
}

