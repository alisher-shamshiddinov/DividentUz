export const SCENARIO_MULTIPLIERS = {
  conservative: 0.65,
  base: 1.0,
  optimistic: 1.3,
}

/**
 * Simulates month-by-month stock price appreciation, optional monthly DCA additions,
 * and optional dividend reinvestment (DRIP) over `years`.
 * All monetary inputs/outputs are in USD for currency-agnostic math.
 */
export function calculateInvestmentProjection({
  stock,
  initialAmountUSD,
  monthlyContributionUSD = 0,
  years = 5,
  drip = true,
  scenario = 'base',
}) {
  if (!stock || initialAmountUSD < 0 || years < 1) {
    return null
  }

  const multiplier = SCENARIO_MULTIPLIERS[scenario] ?? 1.0
  const effectiveAnnualGrowth = (stock.annualGrowthPct / 100) * multiplier
  const dividendYield = stock.dividendYieldPct / 100

  const monthlyPriceRate = Math.pow(1 + effectiveAnnualGrowth, 1 / 12) - 1
  const monthlyDivRate = dividendYield / 12

  let currentPrice = stock.priceUSD
  let shares = currentPrice > 0 ? initialAmountUSD / currentPrice : 0
  let totalContributed = initialAmountUSD
  let totalDividendsEarned = 0
  let cashDividends = 0

  const startingShares = shares
  const yearlyBreakdown = [
    {
      year: 0,
      sharePrice: currentPrice,
      invested: totalContributed,
      shares,
      totalDividendsEarned: 0,
      annualDividendRate: shares * currentPrice * dividendYield,
      totalValue: initialAmountUSD,
      profit: 0,
      profitPct: 0,
    },
  ]

  for (let year = 1; year <= years; year += 1) {
    for (let m = 1; m <= 12; m += 1) {
      currentPrice = currentPrice * (1 + monthlyPriceRate)

      if (monthlyContributionUSD > 0) {
        shares += monthlyContributionUSD / currentPrice
        totalContributed += monthlyContributionUSD
      }

      if (monthlyDivRate > 0) {
        const divPayout = shares * currentPrice * monthlyDivRate
        totalDividendsEarned += divPayout
        if (drip) {
          shares += divPayout / currentPrice
        } else {
          cashDividends += divPayout
        }
      }
    }

    const stockValue = shares * currentPrice
    const totalValue = stockValue + cashDividends
    const profit = totalValue - totalContributed
    const profitPct = totalContributed > 0 ? (profit / totalContributed) * 100 : 0
    const annualDividendRate = shares * currentPrice * dividendYield

    yearlyBreakdown.push({
      year,
      sharePrice: currentPrice,
      invested: totalContributed,
      shares,
      totalDividendsEarned,
      annualDividendRate,
      totalValue,
      profit,
      profitPct,
    })
  }

  const finalPoint = yearlyBreakdown[yearlyBreakdown.length - 1]

  return {
    effectiveAnnualGrowthPct: effectiveAnnualGrowth * 100,
    dividendYieldPct: stock.dividendYieldPct,
    startingShares,
    finalShares: finalPoint.shares,
    finalSharePrice: finalPoint.sharePrice,
    totalInvested: finalPoint.invested,
    finalValue: finalPoint.totalValue,
    netProfit: finalPoint.profit,
    netProfitPct: finalPoint.profitPct,
    totalDividendsEarned: finalPoint.totalDividendsEarned,
    finalAnnualDividend: finalPoint.annualDividendRate,
    finalMonthlyDividend: finalPoint.annualDividendRate / 12,
    yearlyBreakdown,
  }
}
